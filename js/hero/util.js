// Allocation-free vertex normals for an indexed BufferGeometry (much faster than computeVertexNormals).
export function fastNormals(geo) {
  const pos = geo.attributes.position.array;
  let na = geo.attributes.normal;
  const nrm = na.array;
  const idx = geo.index.array;
  nrm.fill(0);
  for (let t = 0, n = idx.length; t < n; t += 3) {
    const a = idx[t] * 3, b = idx[t + 1] * 3, c = idx[t + 2] * 3;
    const abx = pos[b] - pos[a], aby = pos[b + 1] - pos[a + 1], abz = pos[b + 2] - pos[a + 2];
    const acx = pos[c] - pos[a], acy = pos[c + 1] - pos[a + 1], acz = pos[c + 2] - pos[a + 2];
    const x = aby * acz - abz * acy, y = abz * acx - abx * acz, z = abx * acy - aby * acx;
    nrm[a] += x; nrm[a + 1] += y; nrm[a + 2] += z;
    nrm[b] += x; nrm[b + 1] += y; nrm[b + 2] += z;
    nrm[c] += x; nrm[c + 1] += y; nrm[c + 2] += z;
  }
  for (let i = 0, n = nrm.length; i < n; i += 3) {
    const l = Math.sqrt(nrm[i] * nrm[i] + nrm[i + 1] * nrm[i + 1] + nrm[i + 2] * nrm[i + 2]) || 1;
    nrm[i] /= l; nrm[i + 1] /= l; nrm[i + 2] /= l;
  }
  na.needsUpdate = true;
}
